    function qp(k) { return new URLSearchParams(window.location.search).get(k); }

    function relatedCards(ids) {
      return (ids || []).map(id => {
        const a = articles[id]; if (!a) return '';
        return `
          <a href="blog-details.html?id=${id}"
             class="group block border border-gray-800 rounded-2xl overflow-hidden hover:border-orange-500/40 transition-colors duration-300">
            <img src="${a.heroImg}" class="w-full h-32 object-cover" alt="${a.title}" />
            <div class="p-4">
              <span class="text-xs px-3 py-0.5 rounded-full font-medium ${a.tagClass}">${a.tag}</span>
              <h4 class="text-sm font-semibold text-white mt-2 leading-snug group-hover:text-orange-400 transition-colors">${a.title}</h4>
              <p class="text-xs text-gray-500 mt-1">${a.date}</p>
            </div>
          </a>`;
      }).join('');
    }

